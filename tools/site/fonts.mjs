// Copies the web fonts of the site from the npm @fontsource packages (tools/site/package.json) into
// <site>/assets/fonts/ and writes <site>/assets/fonts.css with the matching @font-face rules.
// Only the weights below and the latin / latin-ext subsets are used; woff2 only. Nothing is loaded from a CDN.
// Install the packages with: npm ci --prefix tools/site
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const PKG_DIR = join(here, 'node_modules', '@fontsource');
/** package, weights used by site/assets/style.css */
export const FONTS = [
  { pkg: 'bricolage-grotesque', weights: [700, 800] },
  { pkg: 'atkinson-hyperlegible', weights: [400, 700] },
  { pkg: 'jetbrains-mono', weights: [500, 700] },
];
const SUBSETS = ['latin-ext', 'latin'];

export const fontsInstalled = () => FONTS.every((f) => existsSync(join(PKG_DIR, f.pkg, 'package.json')));

/** Returns { css, files: [[from, toName]] }, or throws when a package lacks a block. */
function plan() {
  const files = [];
  const blocks = [];
  for (const { pkg, weights } of FONTS) {
    for (const w of weights) {
      const css = readFileSync(join(PKG_DIR, pkg, `${w}.css`), 'utf8');
      for (const subset of SUBSETS) {
        const name = `${pkg}-${subset}-${w}-normal`;
        const m = new RegExp(`/\\* ${name} \\*/\\s*@font-face\\s*\\{([^}]*)\\}`).exec(css);
        if (!m) throw new Error(`fonts: ${pkg} ${w} has no ${subset} block`);
        const body = m[1]
          .replace(/src:[^;]*;/, `src: url(/assets/fonts/${name}.woff2) format('woff2');`)
          .split('\n')
          .map((l) => l.trim())
          .filter(Boolean)
          .map((l) => `  ${l}`)
          .join('\n');
        blocks.push(`/* ${name} */\n@font-face {\n${body}\n}`);
        files.push([join(PKG_DIR, pkg, 'files', `${name}.woff2`), `${name}.woff2`]);
      }
    }
  }
  return { css: `/* SPDX-License-Identifier: OFL-1.1 (fonts) / GPL-3.0-or-later (this file). Generated by tools/build-site.mjs from the @fontsource packages. */\n${blocks.join('\n')}\n`, files };
}

export function bundleFonts(assetsDir) {
  const { css, files } = plan();
  const dir = join(assetsDir, 'fonts');
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) rmSync(join(dir, f));
  for (const [from, to] of files) copyFileSync(from, join(dir, to));
  writeFileSync(join(assetsDir, 'fonts.css'), css);
  return files.length;
}
