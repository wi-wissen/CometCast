# Prepares the iOS project on a Mac: after this, `open apps/flutter/ios/Runner.xcworkspace`
# works and `flutter build ios` / `flutter run` can build the app with its Broadcast Extension.
#
#   tools/ios-bootstrap.sh                 everything below
#   tools/ios-bootstrap.sh --no-pods       skip step 6 (no Podfile, no pod install)
#
# Steps:
#   1. check the tools (Xcode, Flutter, rustup, XcodeGen, CocoaPods)
#   2. rustup target add aarch64-apple-ios aarch64-apple-ios-sim x86_64-apple-ios
#   3. flutter config --no-enable-swift-package-manager   (see docs/ios.md; skip with
#      COMETCAST_IOS_KEEP_SPM=1)
#   4. flutter pub get                       (also generates the translations)
#   5. xcodegen generate                     (apps/flutter/ios/project.yml -> Runner.xcodeproj)
#   6. flutter build ios --config-only       (Generated.xcconfig, Podfile, pod install)
# The Rust libraries are NOT built here: each Xcode target builds its own in a build phase
# (tools/ios-build-rust.sh), so a build from Xcode and from `flutter build ios` is the same.
#
# UNCERTAIN: never run (written on Linux). Every command below is a documented command of the
# tool it calls; the order and the Flutter flags are from memory.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
app="$root/apps/flutter"
ios="$app/ios"
pods=1
[ "${1:-}" = "--no-pods" ] && pods=0

need() { command -v "$1" >/dev/null 2>&1 || { echo "missing: $1 ($2)" >&2; missing=1; }; }
missing=0
[ "$(uname -s)" = "Darwin" ] || { echo "iOS builds need macOS with Xcode." >&2; exit 1; }
need xcodebuild "install Xcode and run: sudo xcode-select -s /Applications/Xcode.app"
need flutter "https://docs.flutter.dev/get-started/install/macos/mobile-ios"
need rustup "https://rustup.rs"
need xcodegen "brew install xcodegen"
need pod "brew install cocoapods"
[ "$missing" = 0 ] || exit 1

echo "== Rust targets"
rustup target add aarch64-apple-ios aarch64-apple-ios-sim x86_64-apple-ios

if [ "${COMETCAST_IOS_KEEP_SPM:-0}" != "1" ]; then
  # The project is generated by XcodeGen, not by Flutter: it has no Flutter package references.
  # Flutter's Swift Package Manager integration edits the project file of the template and may
  # fail on a generated one, so plugins come through CocoaPods. This is a GLOBAL Flutter
  # setting (it also applies to the macOS project).
  echo "== flutter config --no-enable-swift-package-manager"
  flutter config --no-enable-swift-package-manager
fi

echo "== flutter pub get"
(cd "$app" && flutter pub get)

if [ ! -f "$ios/Config/Local.xcconfig" ]; then
  cat > "$ios/Config/Local.xcconfig" <<'X'
// Not committed. Your Apple developer team id (10 characters), for signing on a device:
COMETCAST_DEVELOPMENT_TEAM =
X
  echo "created ios/Config/Local.xcconfig: put your team id into it (simulator builds work without)"
fi

echo "== xcodegen generate"
(cd "$ios" && xcodegen generate --spec project.yml)

if [ "$pods" = 1 ]; then
  echo "== flutter build ios --config-only"
  (cd "$app" && flutter build ios --config-only --no-codesign)
fi

cat <<'MSG'

Done. Next:
  open apps/flutter/ios/Runner.xcworkspace
  * Signing: ios/Config/Local.xcconfig (team id), App IDs and App Group: docs/ios.md, "Signing".
  * Run on a device: scheme "Runner". Debug the extension: scheme "BroadcastExtension".
  * Test plan: docs/ios-device-test-plan.md
MSG
