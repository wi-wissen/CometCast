#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-or-later
// Writes the branding constants of the native apps from the selected branding file (branding/README.md):
//   apps/flutter/lib/src/branding.g.dart
//   apps/apple-tv/Sources/CometCastTV/Branding.g.swift
// The file is COMETCAST_BRANDING (default: branding/default.json). The committed files are the default's.
//   node tools/gen-branding.mjs            write
//   node tools/gen-branding.mjs --check    exit 1 when a file differs from what would be written
//   --root DIR                             write below DIR instead of the repository (used by the tests)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { REPO_ROOT, brandingPath, loadBrandingFile } from './branding.mjs';

const dq = (s) => JSON.stringify(s); // double-quoted, escapes " \ and control characters
const dartStr = (s) => dq(s).replace(/\$/g, '\\$');
const swiftStr = (s) => dq(s).replace(/[\u2028\u2029]/g, (c) => `\\u{${c.codePointAt(0).toString(16)}}`);

function constants(b) {
  return [
    ['publisherName', 'publisher_name', b.publisher_name],
    ['publisherUrl', 'publisher_url', b.publisher_url],
    ['privacyUrlDe', 'privacy_url.de', b.privacy_url.de],
    ['privacyUrlEn', 'privacy_url.en', b.privacy_url.en],
    ['imprintUrlDe', 'imprint_url.de', b.imprint_url.de],
    ['imprintUrlEn', 'imprint_url.en', b.imprint_url.en],
    ['sourceUrl', 'source_url', b.source_url],
    ['contact', 'contact', b.contact],
  ];
}

export function renderDart(b, from) {
  const lines = constants(b).map(([n, k, v]) => `  /// \`${k}\`; empty when not set.\n  static const String ${n} = ${dartStr(v)};`);
  return `// GENERATED by tools/gen-branding.mjs from ${from}. Do not edit; see branding/README.md.
// SPDX-License-Identifier: GPL-3.0-or-later

/// Publisher identity and legal links of this build. Empty strings mean "not set": show nothing then.
abstract final class Branding {
${lines.join('\n')}
}
`;
}

export function renderSwift(b, from) {
  const lines = constants(b).map(([n, k, v]) => `    /// \`${k}\`; empty when not set.\n    static let ${n}: String = ${swiftStr(v)}`);
  return `// GENERATED by tools/gen-branding.mjs from ${from}. Do not edit; see branding/README.md.
// SPDX-License-Identifier: GPL-3.0-or-later

/// Publisher identity and legal links of this build. Empty strings mean "not set": show nothing then.
enum Branding {
${lines.join('\n')}
}
`;
}

function main(argv) {
  const check = argv.includes('--check');
  const ri = argv.indexOf('--root');
  const root = ri >= 0 ? argv[ri + 1] : REPO_ROOT;
  if (ri >= 0 && !root) throw new Error('--root needs a folder');
  const file = brandingPath();
  const b = loadBrandingFile(file);
  const rel = relative(REPO_ROOT, file);
  const from = rel.startsWith('..') ? 'a branding file outside the repository' : rel.split('\\').join('/');
  const targets = [
    ['apps/flutter/lib/src/branding.g.dart', renderDart(b, from)],
    ['apps/apple-tv/Sources/CometCastTV/Branding.g.swift', renderSwift(b, from)],
  ];
  let bad = 0;
  for (const [p, text] of targets) {
    const f = join(root, p);
    if (check) {
      let cur = null;
      try {
        cur = readFileSync(f, 'utf8');
      } catch {}
      if (cur !== text) {
        console.error(`${p} is out of date for ${from}: run node tools/gen-branding.mjs`);
        bad++;
      }
    } else {
      mkdirSync(dirname(f), { recursive: true });
      writeFileSync(f, text);
      console.log(`wrote ${p} (from ${from})`);
    }
  }
  if (check) {
    if (bad) process.exit(1);
    console.log(`branding files match ${from}`);
  }
}

try {
  main(process.argv.slice(2));
} catch (e) {
  console.error(`gen-branding: ${e.message}`);
  process.exit(1);
}
